# Pedir un número decimal al usuario
numero = float(input("Introduce un número decimal: "))

# Convertir a entero y a cadena de texto
entero = int(numero)
cadena = str(numero)

print("Número entero:", entero)
print("Cadena de texto:", cadena)

# Convertir una cadena a entero
texto = "5"
numero_convertido = int(texto)

# Realizar una operación aritmética
resultado = numero_convertido + 2

print("Resultado de la suma:", resultado)